#!/usr/bin/env node
/**
 * generate-zone-table — writes packages/skycot-brand/src/zones.generated.ts: every IANA time zone's
 * representative coordinates (its main city, from `zone.tab`) plus the zone-name aliases
 * (`L target alias` lines in `tzdata.zi`), so the mascot can follow the sky of the person's time
 * zone without asking for their location.
 *
 *   node nondev/scripts/generate-zone-table.ts [--zoneinfo /usr/share/zoneinfo]
 *
 * Re-run after a macOS tzdata update; the output is committed. Coordinates are rounded to 0.01°
 * (about 1 km), far finer than the minute of civil-twilight error it could cause.
 */
import * as NodeFS from "node:fs";
import * as NodePath from "node:path";
import * as NodeURL from "node:url";

const ROOT = NodePath.resolve(NodePath.dirname(NodeURL.fileURLToPath(import.meta.url)), "../..");
const OUT = NodePath.join(ROOT, "packages/skycot-brand/src/zones.generated.ts");

const flagIndex = process.argv.indexOf("--zoneinfo");
const zoneinfo = flagIndex >= 0 ? process.argv[flagIndex + 1]! : "/usr/share/zoneinfo";

/** `±DDMM[SS]` / `±DDDMM[SS]` (ISO 6709) to decimal degrees. */
function iso6709(part: string, degreeDigits: number): number {
  const sign = part.startsWith("-") ? -1 : 1;
  const digits = part.slice(1);
  const degrees = Number(digits.slice(0, degreeDigits));
  const minutes = Number(digits.slice(degreeDigits, degreeDigits + 2));
  const seconds = digits.length > degreeDigits + 2 ? Number(digits.slice(degreeDigits + 2)) : 0;
  return sign * (degrees + minutes / 60 + seconds / 3600);
}

function round(value: number): number {
  return Math.round(value * 100) / 100;
}

const coordinates = new Map<string, readonly [number, number]>();
for (const line of NodeFS.readFileSync(NodePath.join(zoneinfo, "zone.tab"), "utf8").split("\n")) {
  if (line.startsWith("#") || line.trim() === "") continue;
  const [, coords, zone] = line.split("\t");
  const match = /^([+-]\d+)([+-]\d+)$/.exec(coords ?? "");
  if (!zone || !match) continue;
  const lat = iso6709(match[1]!, 2);
  const lon = iso6709(match[2]!, 3);
  coordinates.set(zone, [round(lat), round(lon)]);
}

// A zone with its own zone.tab row keeps its own city (Europe/Oslo is a link to Europe/Berlin in
// tzdata, but Oslo's sky is not Berlin's).
const aliases = new Map<string, string>();
for (const line of NodeFS.readFileSync(NodePath.join(zoneinfo, "tzdata.zi"), "utf8").split("\n")) {
  const parts = line.trim().split(/\s+/);
  if (parts[0] !== "L" || parts.length < 3) continue;
  const [, target, alias] = parts as [string, string, string];
  if (coordinates.has(alias) || !coordinates.has(target)) continue;
  aliases.set(alias, target);
}

const version = NodeFS.existsSync(NodePath.join(zoneinfo, "+VERSION"))
  ? NodeFS.readFileSync(NodePath.join(zoneinfo, "+VERSION"), "utf8").trim()
  : "unknown";

/** Quote a key only when the formatter would, so the committed file is already `vp fmt`-clean. */
const key = (name: string) => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name));

const sortedEntries = <T>(map: Map<string, T>) =>
  [...map.entries()].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));

const out = [
  "// Generated by nondev/scripts/generate-zone-table.ts from the macOS tz database " +
    `(${version}): zone.tab coordinates and tzdata.zi links. Do not edit by hand.`,
  "",
  "/** IANA zone → [latitude, longitude] of its main city, degrees (north and east positive). */",
  "export const ZONE_COORDINATES: Readonly<Record<string, readonly [number, number]>> = {",
  ...sortedEntries(coordinates).map(([zone, [lat, lon]]) => `  ${key(zone)}: [${lat}, ${lon}],`),
  "};",
  "",
  "/** Old or alternative zone names → the zone whose coordinates they share. */",
  "export const ZONE_ALIASES: Readonly<Record<string, string>> = {",
  ...sortedEntries(aliases).map(([alias, target]) => `  ${key(alias)}: "${target}",`),
  "};",
  "",
].join("\n");

NodeFS.writeFileSync(OUT, out);
process.stdout.write(
  `generate-zone-table: ${coordinates.size} zones, ${aliases.size} aliases → ${NodePath.relative(ROOT, OUT)}\n`,
);
