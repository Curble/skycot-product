#!/usr/bin/env node
/**
 * sync-brand-assets — copies the brand files the apps ship from nondev/brand/assets (the source
 * of truth) into the apps that bundle them, so a redrawn mascot lands everywhere with one command.
 *
 *   node nondev/scripts/sync-brand-assets.ts           write the copies
 *   node nondev/scripts/sync-brand-assets.ts --check   exit 1 if any copy is missing or stale
 *
 * What goes where:
 *   apps/nondev/src/assets/brand/   the six poses (day + dusk SVG), the day/dusk SVG favicons and
 *                                   the apple-touch icon; Vite fingerprints them into dist/.
 *   apps/desktop/src/skycot/dockIcons.generated.ts
 *                                   the 512 px day and dusk macOS icons as base64, bundled into
 *                                   main.cjs. A Dock tile tops out at 256 pt (512 px on Retina),
 *                                   and embedding means the packaged app needs no extra resource
 *                                   files (no seam in the electron-builder resource list).
 */
import * as NodeFS from "node:fs";
import * as NodePath from "node:path";
import * as NodeURL from "node:url";

export const ROOT = NodePath.resolve(
  NodePath.dirname(NodeURL.fileURLToPath(import.meta.url)),
  "../..",
);
const SOURCE = "nondev/brand/assets";
const CLIENT_DIR = "apps/nondev/src/assets/brand";
const DOCK_MODULE = "apps/desktop/src/skycot/dockIcons.generated.ts";

export const POSES = ["hello", "yay", "ask-a-grown-up", "thinking", "oops", "night-night"] as const;
const PHASES = ["day", "dusk"] as const;

export interface PlannedFile {
  /** Repo-relative. */
  readonly target: string;
  readonly contents: Buffer;
}

function read(relativePath: string): Buffer {
  return NodeFS.readFileSync(NodePath.join(ROOT, relativePath));
}

export function plannedFiles(): PlannedFile[] {
  const files: PlannedFile[] = [];
  for (const phase of PHASES) {
    for (const pose of POSES) {
      const name = `mascot-${pose}-${phase}.svg`;
      files.push({
        target: `${CLIENT_DIR}/${name}`,
        contents: read(`${SOURCE}/poses/${phase}/${name}`),
      });
    }
    files.push({
      target: `${CLIENT_DIR}/favicon-${phase}.svg`,
      contents: read(`${SOURCE}/web/favicon-${phase}.svg`),
    });
  }
  files.push({
    target: `${CLIENT_DIR}/apple-touch-icon-day.png`,
    contents: read(`${SOURCE}/web/apple-touch-icon-day.png`),
  });

  const dock = (phase: (typeof PHASES)[number]) =>
    read(`${SOURCE}/macos/AppIcon-${phase}.iconset/icon_256x256@2x.png`).toString("base64");
  files.push({
    target: DOCK_MODULE,
    contents: Buffer.from(
      [
        "// Generated by nondev/scripts/sync-brand-assets.ts from nondev/brand/assets/macos/",
        "// AppIcon-{day,dusk}.iconset/icon_256x256@2x.png (512 px). Do not edit by hand.",
        "",
        `export const DOCK_ICON_DAY_PNG_BASE64 =\n  "${dock("day")}";`,
        "",
        `export const DOCK_ICON_DUSK_PNG_BASE64 =\n  "${dock("dusk")}";`,
        "",
      ].join("\n"),
    ),
  });
  return files;
}

/** Repo-relative targets whose bytes differ from the source (or are missing). */
export function staleFiles(files = plannedFiles()): string[] {
  return files
    .filter(({ target, contents }) => {
      const absolute = NodePath.join(ROOT, target);
      return !NodeFS.existsSync(absolute) || !NodeFS.readFileSync(absolute).equals(contents);
    })
    .map(({ target }) => target);
}

function main(): number {
  const files = plannedFiles();
  const stale = staleFiles(files);
  if (process.argv.includes("--check")) {
    if (stale.length === 0) {
      process.stdout.write(`sync-brand-assets: ${files.length} copies match nondev/brand/assets\n`);
      return 0;
    }
    process.stderr.write(
      `sync-brand-assets: ${stale.length} stale copy(ies); run node nondev/scripts/sync-brand-assets.ts\n` +
        stale.map((target) => `  - ${target}`).join("\n") +
        "\n",
    );
    return 1;
  }
  for (const { target, contents } of files) {
    if (!stale.includes(target)) continue;
    const absolute = NodePath.join(ROOT, target);
    NodeFS.mkdirSync(NodePath.dirname(absolute), { recursive: true });
    NodeFS.writeFileSync(absolute, contents);
  }
  process.stdout.write(`sync-brand-assets: wrote ${stale.length} of ${files.length} files\n`);
  return 0;
}

if (import.meta.url === NodeURL.pathToFileURL(process.argv[1] ?? "").href) process.exit(main());
